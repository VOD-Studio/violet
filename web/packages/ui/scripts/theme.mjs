import { execFileSync } from "node:child_process";
import { build } from "esbuild";
import { packageRoot } from "./registry.mjs";

const header = "/* Generated by pnpm --filter @violet/ui sync; edit scripts/theme.mjs instead. */\n";
const palettes = { violet: "#684dda", coral: "#e65853" };

export async function generatedThemeSources() {
	const result = await build({
		absWorkingDir: packageRoot,
		stdin: { contents: 'export { generateScales, toCssVariables } from "@violetjs/theme";', resolveDir: packageRoot, loader: "ts" },
		bundle: true,
		write: false,
		platform: "node",
		format: "esm",
		logLevel: "silent",
	});
	const { generateScales, toCssVariables } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString("base64")}`);
	const combinations = (themeForAppearance, appearances = ["light", "dark"]) => appearances.flatMap((appearance) =>
		["standard", "more"].map((contrast) => generateScales(themeForAppearance(appearance), { appearance, contrast })),
	);
	const neutralOnly = (css) => css.split("\n").filter((line) => !/^\s*--/.test(line) || /^\s*--(?:action|immersive)-neutral-/.test(line)).join("\n");
	const sources = new Map(Object.entries(palettes).map(([name, seed]) => [
		`src/styles/palettes/${name}.generated.css`,
		header + toCssVariables(combinations(() => ({ version: 1, seed })), { selector: `:root,\n[data-theme="${name}"]` }),
	]));
	const action = combinations((appearance) => ({ version: 1, seed: appearance === "light" ? "#202020" : "#eeeeee", knobs: { neutralChroma: 0 } }));
	const immersive = combinations(() => ({ version: 1, seed: "#eeeeee", knobs: { neutralChroma: 0 } }), ["dark"]);
	sources.set("src/styles/fixed.generated.css", header + neutralOnly(toCssVariables(action, { prefix: "action-" })) + "\n" + neutralOnly(toCssVariables(immersive, { prefix: "immersive-" })));
	return new Map([...sources].map(([path, content]) => [path, execFileSync("pnpm", ["exec", "biome", "format", `--stdin-file-path=${path}`], { cwd: packageRoot, input: content, encoding: "utf8" })]));
}
