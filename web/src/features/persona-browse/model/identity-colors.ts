import { type ContrastLevel, generateScales } from "@violetjs/theme";

/**
 * 将人设种子色映射为局部身份语义，供构建期生成静态 CSS。
 *
 * @param seed - 人设身份种子色，不继承站点品牌色
 * @returns 同时覆盖深浅外观与提高对比度偏好的局部变量
 */
export function generatePersonaIdentityCss(seed: string): string {
	const block = (contrast: ContrastLevel, indent: string) => {
		const light = generateScales({ version: 1, seed }, { appearance: "light", contrast });
		const dark = generateScales({ version: 1, seed }, { appearance: "dark", contrast });
		const roles = {
			text: [light.brand.steps[11], dark.brand.steps[11]],
			border: [light.brand.steps[7], dark.brand.steps[7]],
			decoration: [light.brand.steps[9], dark.brand.steps[9]],
			surface: [light.brand.steps[3], dark.brand.steps[3]],
		};
		return [
			`${indent}.identity-theme {`,
			...Object.entries(roles).map(
				([role, [lightColor, darkColor]]) =>
					`${indent}\t--identity-${role}: light-dark(${lightColor}, ${darkColor});`,
			),
			`${indent}}`,
		].join("\n");
	};
	return [
		"/* Generated by scripts/sync-persona-colors.mjs. Do not edit. */",
		block("standard", ""),
		"",
		"@media (prefers-contrast: more) {",
		block("more", "\t"),
		"}",
		"",
	].join("\n");
}
