/**
 * 站点作者手写签名笔画预置数据
 *
 * 遵循数据与渲染分离规范：所有名字的真实矢量笔画、viewBox 与书写时序
 * 集中在此文件统一定义。未来更换或新增手写签名，只需在此增改对应条目。
 */

export interface StrokeData {
	/** SVG 矢量笔画路径数据（M/C 曲线） */
	d: string;
	/** 运笔绘制时长（秒） */
	duration: number;
	/** 相对起笔延迟（秒） */
	delay: number;
	/** 笔划线宽，默认 3 */
	width?: number;
}

export interface SignaturePreset {
	/** 标识名字（全小写规范化） */
	name: string;
	/** SVG 视口尺寸 */
	viewBox: string;
	/** 原始参考宽度 */
	width: number;
	/** 原始参考高度 */
	height: number;
	/** 按真实书写笔顺排列的连续矢量笔画组 */
	strokes: StrokeData[];
}

