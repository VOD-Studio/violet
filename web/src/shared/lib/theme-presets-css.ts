import { generateScales, toCssVariables } from "@violetjs/theme";

import { SEASONS } from "./theme-preference";
import { THEME_PRESETS } from "./theme-presets";

/** 状态色与分类色不随主题变化，组件包的默认色板已在 :root 定义，预设里省掉以减小样式表。 */
const FIXED_SCALE = /^\s*--(?:danger|warning|success|category-\d)-/;

/**
 * 生成四季预设主题的静态 CSS，供构建期写入样式表。
 *
 * @returns 每季一个 `[data-theme="季节"]` 规则，含明暗与提高对比度两档的品牌、中性色阶
 */
export function generateThemePresetsCss(): string {
	const blocks = SEASONS.map((season) => {
		const { seed, knobs } = THEME_PRESETS[season];
		const scales = (["light", "dark"] as const).flatMap((appearance) =>
			(["standard", "more"] as const).map((contrast) =>
				generateScales({ version: 1, seed, knobs }, { appearance, contrast }),
			),
		);
		return toCssVariables(scales, { selector: `[data-theme="${season}"]` })
			.split("\n")
			.filter((line) => !FIXED_SCALE.test(line))
			.join("\n");
	});
	return ["/* Generated by scripts/sync-theme-presets.mjs. Do not edit. */", ...blocks, ""].join(
		"\n\n",
	);
}
