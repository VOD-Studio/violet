import { generateThemeCss } from "./theme-css";
import { SEASONS } from "./theme-preference";
import { THEME_PRESETS } from "./theme-presets";

/**
 * 生成四季预设主题的静态 CSS，供构建期写入样式表。
 *
 * @returns 每季一个 `[data-theme="季节"]` 规则，含明暗与提高对比度两档的品牌、中性色阶
 */
export function generateThemePresetsCss(): string {
	const blocks = SEASONS.map((season) => {
		const { seed, knobs } = THEME_PRESETS[season];
		return generateThemeCss({ version: 1, seed, knobs }, `[data-theme="${season}"]`);
	});
	return ["/* Generated by scripts/sync-theme-presets.mjs. Do not edit. */", ...blocks, ""].join(
		"\n\n",
	);
}
